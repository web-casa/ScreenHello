import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';
import { extractStyle } from '@ant-design/static-style-extract';
import ts from 'typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = resolve(root, 'src/style/antd-static.css');

// Keep this list aligned with the named imports from `antd` in `src/`.  Ant
// Design 6 disables runtime component-style injection when StyleProvider uses
// a cascade layer, so these rules are part of the application bundle rather
// than an optional optimization.
const components = [
    'Alert', 'Button', 'ColorPicker', 'Divider', 'Drawer', 'Dropdown', 'Empty',
    'Input', 'InputNumber', 'Menu', 'Modal', 'Popover', 'Popconfirm', 'Radio',
    'Segmented', 'Select', 'Slider', 'Spin', 'Switch', 'Tabs', 'Tag', 'Tooltip',
    'message',
];

const STYLELESS_ANTD_EXPORTS = new Set(['ConfigProvider', 'theme']);
const walkSource = (directory) => readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) return walkSource(path);
    return /\.(?:js|jsx)$/.test(entry.name) ? [path] : [];
});

const importedAntdExports = new Set();
for (const file of walkSource(resolve(root, 'src'))) {
    const source = ts.createSourceFile(file, readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true,
        file.endsWith('.jsx') ? ts.ScriptKind.JSX : ts.ScriptKind.JS);
    for (const statement of source.statements) {
        if (!ts.isImportDeclaration(statement) || statement.moduleSpecifier.text !== 'antd') continue;
        const bindings = statement.importClause?.namedBindings;
        if (!bindings || !ts.isNamedImports(bindings)) continue;
        for (const specifier of bindings.elements) importedAntdExports.add(specifier.propertyName?.text ?? specifier.name.text);
    }
}

const uncoveredImports = [...importedAntdExports]
    .filter((name) => !STYLELESS_ANTD_EXPORTS.has(name) && !components.includes(name));
if (uncoveredImports.length) {
    throw new Error(`antd-static-css-component-missing:${uncoveredImports.sort().join(',')}`);
}

const source = extractStyle({ includes: components });
const scopeMatch = source.match(/css-dev-only-do-not-override-([a-z0-9]+)/i);

if (!scopeMatch) throw new Error('antd-static-css-development-scope-not-found');

const [, hash] = scopeMatch;
const developmentScope = `.css-dev-only-do-not-override-${hash}`;
const productionScope = `.css-${hash}`;
// cssinjs adds a readable development class and a compact production class.
// One selector keeps the committed CSS usable in both modes without including
// two complete copies of the extracted rules.
const css = `/* Generated by scripts/generate-antd-static-css.mjs. Do not edit manually. */\n${source.replaceAll(
    `:where(${developmentScope})`,
    `:where(${developmentScope}, ${productionScope})`,
)}\n`;

if (process.argv.includes('--check')) {
    if (readFileSync(output, 'utf8') !== css) {
        throw new Error('antd-static-css-out-of-date: run pnpm generate:antd-css');
    }
    console.log(JSON.stringify({ output: 'src/style/antd-static.css', bytes: Buffer.byteLength(css), status: 'current' }));
} else {
    writeFileSync(output, css);
    console.log(JSON.stringify({ output: 'src/style/antd-static.css', bytes: Buffer.byteLength(css), components }));
}
